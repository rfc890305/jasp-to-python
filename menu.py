@dataclass
class Item:
    label: str
    jasp: str = "⬜"
    page: str | None = None
    path: str = ""
    trail: tuple[str, ...] = ()


@dataclass
class Node:
    label: str
    children: list = field(default_factory=list)
    path: str = ""


def I(label, jasp="⬜", page=None):  # noqa: E743 - nome curto deixa a árvore legível
    return Item(label, jasp, page)


def N(label, *children):
    return Node(label, list(children))


